/** 判断是否像一条 owner 指令（用于决定要不要给引导）。 */
export function looksLikeOwnerCommandAttempt(text) {
  const raw = String(text ?? '').trim();
  if (!raw) return false;
  const s = normalize(raw);
  if (!s) return false;
  const compact = s.replace(/\s+/g, '');

  const stems = [
    /^(?:资料卡点赞|名片点赞|资料卡赞|名片赞)/,
    /^(?:好友申请|申请列表|通过申请|同意申请|接受申请|拒绝申请|驳回申请|好友来源|来源查询)/,
    /^(?:查看)?待处理评论|^待评论(?:确认|取消)|^评论队列/,
    /^(?:状态|运行状态|机器人状态|会话列表|对话列表|群列表|群聊列表|我的群|群成员|查看群成员|最近错误|错误日志|最近异常|余额|deepseek余额|查询余额|提醒列表|定时提醒|取消提醒|删除提醒|控制台|群荣誉|@?全体剩余)/i,
    /^(?:入群申请|入群请求|加群申请|通过入群|同意入群|拒绝入群|驳回入群|踢人|禁言|解禁|解除禁言|全员禁言|改名片|改群名|设管理|群头衔|设置头衔|设精华|设置精华|加精|取消精华|移出精华|取消加精|群签到|退群|撤回|查qq|改备注|删好友|管理帮助|管理员帮助|管理指令)/i,
    /^(?:消息表情回应|取消表情回应|主动唤醒|主动对话|主动发言|主动联系|主动状态|主动开关|关闭主动|开启主动|限额调整|调整限额|发送限额|限额重置|重置限额|定时任务|预约任务|定时发言|查询模型余额|模型余额)/i,
    /^(?:查看你?全部好友|查看你?所有好友|好友列表|全部好友|所有好友)/,
    /^(?:查看你?最近最活跃|最近最活跃)/,
    /^查看群聊|^查看群消息|^群聊记录|^群聊(?:查看|转发|记录)帮助/,
    /^查看.{0,40}(?:最近.{0,12}(?:条|对话|聊天|消息|记录)|\d+条(?:对话|聊天|消息|记录))/,
    /^查看.{0,40}(?:的)?(?:空间|说说|动态|朋友圈)/,
    /^(?:查看好友动态|好友动态查询)/,
    /^(?:指令|帮助|命令|功能|指令帮助|命令帮助|全部指令|所有指令|功能列表)$/
  ];
  if (stems.some((re) => re.test(compact))) return true;

  // 方括号开头、且第一段以命令词开头：例如 [查看你全部好友啊]。
  const firstSeg = raw.match(/^\s*[\[【]([^\]】]+)[\]】]/)?.[1]?.trim() || '';
  if (firstSeg && /^(?:查看|好友|资料卡|名片|通过|拒绝|同意|申请|指令|帮助)/.test(firstSeg)) {
    return true;
  }
  return false;
}

/** 返回对应指令族的引导文本；不像指令时返回空字符串。 */
export function buildOwnerCommandGuide(text) {
  if (!looksLikeOwnerCommandAttempt(text)) return '';
  const compact = normalize(text).replace(/\s+/g, '');
  if (/(?:待处理评论|待评论|评论队列)/.test(compact)) return PENDING_COMMENT_GUIDE;
  if (/(?:消息表情回应|取消表情回应|主动唤醒|主动对话|主动发言|主动联系|主动状态|主动开关|关闭主动|开启主动|限额调整|调整限额|发送限额|限额重置|重置限额|定时任务|预约任务|定时发言|查询模型余额|模型余额)/i.test(compact)) {
    return OWNER_ACTION_GUIDE;
  }
  if (/(?:入群申请|入群请求|加群申请|通过入群|同意入群|拒绝入群|驳回入群|踢人|禁言|解禁|解除禁言|全员禁言|改名片|改群名|设管理|群头衔|设置头衔|设精华|设置精华|加精|取消精华|移出精华|取消加精|群签到|退群|撤回|查qq|改备注|删好友|管理帮助|管理员帮助|管理指令)/i.test(compact)) {
    return ADMIN_GUIDE;
  }
  if (/(?:查看群聊|查看群消息|群聊记录|群聊查看|群聊转发)/.test(compact)) return GROUP_VIEW_GUIDE;
  if (/(?:状态|会话列表|对话列表|群列表|群聊列表|群成员|最近错误|错误日志|余额|deepseek余额|查询余额|提醒列表|定时提醒|取消提醒|控制台|群荣誉|@?全体剩余)/i.test(compact)) {
    return CONSOLE_GUIDE;
  }
  if (/(?:资料卡|名片)(?:点赞|赞)/.test(compact)) return PROFILE_LIKE_GUIDE;
  if (/(?:申请|好友来源)/.test(compact)) return FRIEND_REQUEST_GUIDE;
  if (/(?:最近最活跃|全部好友|所有好友|好友列表|最近.{0,12}(?:条|对话|聊天|消息|记录)|\d+条(?:对话|聊天|消息|记录))/.test(compact)) {
    return FRIEND_VIEW_GUIDE;
  }
  if (/(?:动态|说说|空间|朋友圈)/.test(compact)) return FEED_QUERY_GUIDE;
  return GENERIC_GUIDE;
}
